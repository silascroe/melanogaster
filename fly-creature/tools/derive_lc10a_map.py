"""Derive an experimental LC10a spatial-input map from MaleCNS SWC skeletons.

The official SWCs are read-only inputs. Their distal optic-lobe point window is
a geometric heuristic, not a registered lobula ROI or measured receptive field.
The resulting compact JSON is a hypothesis suitable for controlled probes.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np


OPTIC_WINDOW_MAX_Y = 20000.0
OPTIC_WINDOW_MAX_Z = 26000.0
MIN_POINTS = 100
FRONTAL_CENTER_DEG = 5.0
LATERAL_CENTER_DEG = 60.0
SWC_SOURCE = ("https://storage.googleapis.com/flyem-male-cns/v1.0/"
              "segmentation/skeletons-malecns/skeletons-swc/{body_id}.swc")


def derive(circuit_path: Path, skeleton_dir: Path) -> dict:
    source = circuit_path.read_bytes()
    circuit = json.loads(source)
    neurons = [n for n in circuit["neurons"] if n["type"] == "LC10a"]
    if len(neurons) != 275 or {n["side"] for n in neurons} != {"L", "R"}:
        raise ValueError("Expected the packaged 275-cell bilateral LC10a selection")
    rows = []
    skeleton_digest = hashlib.sha256()
    for neuron in neurons:
        body_id = int(neuron["body_id"])
        content = (skeleton_dir / f"{body_id}.swc").read_bytes()
        if not content.startswith(b"#Generated by NeuTu"):
            raise ValueError(f"Unexpected MaleCNS skeleton format: {body_id}")
        skeleton_digest.update(str(body_id).encode("ascii") + b"\0")
        skeleton_digest.update(hashlib.sha256(content).digest())
        points = np.loadtxt(skeleton_dir / f"{body_id}.swc", comments="#")
        if points.ndim != 2 or points.shape[1] != 7:
            raise ValueError(f"Invalid SWC point table: {body_id}")
        # Source coordinates are in MaleCNS 8 nm voxel units. The observed
        # LC10a distal arbor forms a separated low-y/low-z cluster. This box
        # is a reproducible heuristic, not an official lobula segmentation.
        distal = points[(points[:, 3] < OPTIC_WINDOW_MAX_Y)
                        & (points[:, 4] < OPTIC_WINDOW_MAX_Z)]
        if len(distal) < MIN_POINTS:
            raise ValueError(f"Too few distal arbor points for {body_id}: {len(distal)}")
        rows.append({"body_id": body_id, "side": neuron["side"],
                     "distal_point_count": len(distal),
                     "distal_median_y_vox": float(np.median(distal[:, 3]))})
    for side in ("L", "R"):
        selected = sorted((r for r in rows if r["side"] == side),
                          key=lambda r: (r["distal_median_y_vox"], r["body_id"]))
        if len(selected) < 2:
            raise ValueError(f"Missing LC10a side {side}")
        # Equal medians get the same midpoint rank; body ID breaks the sort
        # only for deterministic JSON ordering, not for the map itself.
        i = 0
        while i < len(selected):
            j = i + 1
            while (j < len(selected) and selected[j]["distal_median_y_vox"]
                   == selected[i]["distal_median_y_vox"]):
                j += 1
            rank = ((i + j - 1) / 2) / (len(selected) - 1)
            center = FRONTAL_CENTER_DEG + (LATERAL_CENTER_DEG - FRONTAL_CENTER_DEG) * rank
            for row in selected[i:j]:
                row["preferred_abs_bearing_deg"] = round(center, 4)
            i = j
    types = {int(n["body_id"]): n["type"] for n in circuit["neurons"]}
    aotu_weights = {row["body_id"]: {"AOTU019": 0, "AOTU025": 0}
                    for row in rows}
    for edge in circuit["connections"]:
        if edge["pre"] in aotu_weights and types[edge["post"]] in ("AOTU019", "AOTU025"):
            aotu_weights[edge["pre"]][types[edge["post"]]] += edge["synapse_count"]
    axis_crosscheck = {}
    for side in ("L", "R"):
        selected = [row for row in rows if row["side"] == side]
        y = np.asarray([row["distal_median_y_vox"] for row in selected])
        fraction = np.asarray([
            (aotu_weights[row["body_id"]]["AOTU019"] /
             sum(aotu_weights[row["body_id"]].values()))
            if sum(aotu_weights[row["body_id"]].values()) else 0.5
            for row in selected
        ])
        axis_crosscheck[side] = {
            "n": len(selected),
            "pearson_y_vs_AOTU019_fraction": round(float(np.corrcoef(y, fraction)[0, 1]), 4),
            "zero_selected_AOTU_edges": sum(
                sum(aotu_weights[row["body_id"]].values()) == 0 for row in selected),
        }
    return {
        "schema_version": 1,
        "status": "anatomical input hypothesis, not measured per-cell receptive fields",
        "sources": {
            "release": "FlyEM Male CNS v1.0",
            "swc_url_template": SWC_SOURCE,
            "circuit_sha256": hashlib.sha256(source).hexdigest(),
            "ordered_skeleton_sha256": skeleton_digest.hexdigest(),
        },
        "method": {
            "coordinates": "MaleCNS 8 nm voxels",
            "distal_window": {"y_lt": OPTIC_WINDOW_MAX_Y, "z_lt": OPTIC_WINDOW_MAX_Z},
            "position": "median y of SWC points in the distal window",
            "assignment": "within-side rank mapped linearly from 5 to 60 degrees absolute bearing; "
                          "low y is provisionally frontal",
            "orientation_evidence": "Low-y LC10a cells preferentially contact AOTU019 in this release; "
                                    "published FAFB anatomy and male physiology associate AOTU019 "
                                    "with more frontal and AOTU025 with more lateral responses. "
                                    "This is an inferred cross-dataset orientation, not an optic registration.",
            "limits": "SWC geometry is independent of the packaged edge weights, but the "
                      "axis orientation and angle range are assumptions; point density "
                      "and this geometric window are not measured receptive fields.",
        },
        "axis_crosscheck": axis_crosscheck,
        "cells": sorted(rows, key=lambda r: r["body_id"]),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--circuit", type=Path,
                        default=Path("src/fly_creature/data/visual_steering_v1.json"))
    parser.add_argument("--skeleton-dir", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    result = derive(args.circuit, args.skeleton_dir)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"cells": len(result["cells"]), "left": sum(
        r["side"] == "L" for r in result["cells"]), "right": sum(
        r["side"] == "R" for r in result["cells"]),
        "sha256": result["sources"]["ordered_skeleton_sha256"]}))


if __name__ == "__main__":
    main()
