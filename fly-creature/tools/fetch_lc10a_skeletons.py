"""Download selected official MaleCNS LC10a SWCs for offline research.

Raw skeletons belong in ignored outputs, not in the portable runtime package.
Source: https://male-cns.janelia.org/download/
"""

from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import json
from pathlib import Path
from urllib.request import urlopen


URL = ("https://storage.googleapis.com/flyem-male-cns/v1.0/segmentation/"
       "skeletons-malecns/skeletons-swc/{body_id}.swc")


def fetch(body_id: int, output_dir: Path) -> int:
    path = output_dir / f"{body_id}.swc"
    if path.exists() and path.stat().st_size > 1000:
        return path.stat().st_size
    with urlopen(URL.format(body_id=body_id), timeout=30) as response:
        content = response.read()
    if len(content) <= 1000 or not content.startswith(b"#Generated by NeuTu"):
        raise ValueError(f"Unexpected skeleton content for body {body_id}")
    path.write_bytes(content)
    return len(content)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--circuit", type=Path,
                        default=Path("src/fly_creature/data/visual_steering_v1.json"))
    parser.add_argument("--output-dir", type=Path, default=Path("outputs/lc10a_skeletons"))
    args = parser.parse_args()
    payload = json.loads(args.circuit.read_text(encoding="utf-8"))
    ids = [int(row["body_id"]) for row in payload["neurons"] if row["type"] == "LC10a"]
    if len(ids) != 275 or len(set(ids)) != len(ids):
        raise ValueError("Expected 275 unique LC10a body IDs")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(max_workers=8) as pool:
        sizes = [future.result() for future in as_completed(
            [pool.submit(fetch, body_id, args.output_dir) for body_id in ids])]
    print(json.dumps({"skeletons": len(sizes), "bytes": sum(sizes),
                      "smallest_bytes": min(sizes), "largest_bytes": max(sizes)}))


if __name__ == "__main__":
    main()
